// Bundles supabase/functions/carb-benchmark/core.ts (the app's own benchmark, absorption, insulin and trend code)
// into one file the Deno function can import: one source of truth, no hand-made copy.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
export const OPTIONS = {
  entryPoints: ['supabase/functions/carb-benchmark/core.ts'], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  outfile: 'supabase/functions/carb-benchmark/bench.js', legalComments: 'none',
  banner: { js: '// GENERATED by scripts/bundle-benchmark.mjs from src/engine — do not edit.' },
};
// --check: fail when bench.js is not what src/engine bundles to today (the server would run old maths)
if (process.argv.includes('--check')) {
  const out = await build({ ...OPTIONS, write: false });
  if (out.outputFiles[0].text !== readFileSync(OPTIONS.outfile, 'utf8')) { console.error('bench.js is out of date: run node scripts/bundle-benchmark.mjs and redeploy carb-benchmark'); process.exit(1); }
  console.log('bench.js matches src/engine');
} else { await build(OPTIONS); console.log('bundled', OPTIONS.outfile); }
